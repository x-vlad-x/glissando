#!/usr/bin/env python3
"""Generate THIRD-PARTY.md: the crates linked into the shipped binaries.

The crates come from `cargo tree` for the arm64 target and their details from
`cargo metadata`. Build dependencies and proc-macro crates are left out, since
none of their code ends up in a binary. Licence texts are copied from the crate
sources in the Cargo registry, so run this after the crates have been fetched.

    tools/third-party.py           rewrite THIRD-PARTY.md
    tools/third-party.py --check   fail if THIRD-PARTY.md is out of date
"""
import argparse
import json
import os
import re
import subprocess
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "THIRD-PARTY.md"
TARGET = "aarch64-unknown-linux-gnu"
# Workspace crate of each shipped binary, and the package it is shipped in.
SHIPPED = {
    "glissando": "glissando",
    "glissando-settings": "glissando",
    "glissando-voice": "glissando-voice",
}
LICENCE_FILE = re.compile(r"^(licen[cs]e|unlicense|copying|copyright|notice)([-_.][^/]*)?$", re.I)
SKIPPED_SUFFIXES = (".rs", ".toml", ".json")

HEADER = """\
# Third-party licences

The binaries in the `glissando` and `glissando-voice` packages statically link
the Rust crates below. This file is generated by `tools/third-party.py` from
`Cargo.lock`; do not edit it by hand.

Where a crate offers a choice of licences, every text it ships is included.

The Rust standard library is linked into the same binaries and is available
under `MIT OR Apache-2.0`; see
<https://github.com/rust-lang/rust/blob/master/COPYRIGHT>. Shared system
libraries are not linked statically and are not listed here. `whisper-cli` and
the speech model are covered by the `copyright` file of `glissando-voice`.
"""


def metadata():
    out = subprocess.check_output(
        ["cargo", "metadata", "--locked", "--offline", "--format-version", "1", "--filter-platform", TARGET],
        cwd=ROOT,
    )
    return json.loads(out)


def linked_crates(meta):
    """Map each linked third-party package to the packages shipping it."""
    packages = {(p["name"], p["version"]): p for p in meta["packages"]}
    workspace = {p["name"] for p in meta["packages"] if p["id"] in meta["workspace_members"]}
    linked = defaultdict(set)
    # cargo tree resolves features for these binaries alone; the resolve graph
    # in the metadata unifies them across the workspace and lists too much.
    for crate, shipped_in in SHIPPED.items():
        tree = subprocess.check_output(
            ["cargo", "tree", "--locked", "--offline", "--target", TARGET, "--edges", "normal,no-proc-macro",
             "--package", crate, "--prefix", "none", "--format", "{p}", "--color", "never"],
            cwd=ROOT, text=True,
        )
        for line in tree.splitlines():
            name, version = line.split()[:2]
            if name not in workspace:
                linked[name, version.removeprefix("v")].add(shipped_in)
    return [(packages[key], sorted(shipped)) for key, shipped in linked.items()]


def licence_files(crate_dir):
    found = []
    for directory, subdirs, files in os.walk(crate_dir):
        subdirs.sort()
        for name in sorted(files):
            if LICENCE_FILE.match(name) and not name.endswith(SKIPPED_SUFFIXES):
                found.append(Path(directory, name))
    return found


def render(crates):
    rows, texts = [], {}
    for package, shipped in sorted(crates, key=lambda c: (c[0]["name"], c[0]["version"])):
        label = f'{package["name"]} {package["version"]}'
        licence = package["license"] or "see licence text"
        source = package.get("repository") or ""
        rows.append(f'| {package["name"]} | {package["version"]} | {licence} | {", ".join(shipped)} | {source} |')
        crate_dir = Path(package["manifest_path"]).parent
        files = licence_files(crate_dir)
        if not files:
            sys.exit(f"{label}: no licence file in {crate_dir}")
        for path in files:
            text = path.read_text(encoding="utf-8").strip("\n")
            text = "\n".join(line.rstrip() for line in text.splitlines())
            texts.setdefault(text, []).append(f"{label} (`{path.relative_to(crate_dir)}`)")

    out = [HEADER, "## Crates\n", "| Crate | Version | Licence | Package | Source |", "|---|---|---|---|---|"]
    out += rows
    out += ["", "## Licence texts"]
    for number, (text, users) in enumerate(sorted(texts.items(), key=lambda t: t[1][0]), 1):
        out += ["", f"### Text {number}", "", "Used by:", ""]
        out += [f"- {user}" for user in users]
        out += ["", "````text", text, "````"]
    return "\n".join(out) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail if THIRD-PARTY.md is out of date")
    args = parser.parse_args()
    content = render(linked_crates(metadata()))
    if not args.check:
        OUTPUT.write_text(content, encoding="utf-8")
        return
    if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != content:
        sys.exit("THIRD-PARTY.md is out of date: run tools/third-party.py")


if __name__ == "__main__":
    main()
